#!/usr/bin/env bun

/**
 * Generate rule-bearing outputs from the rules source in rules/.
 *
 * Every rule is one record, rules/<domain>/<id>.md (see rules/README.md and
 * docs/design/rules-source.md). This tool validates the records and writes:
 *
 *   - rules/INDEX.md: one table per domain;
 *   - the generated regions of ssl-style-guide/ssl-style-guide.schema.yaml,
 *     built from rules/schema-base.yaml plus the records' `schema`
 *     placements (the subtrees named in rules/schema-base.yaml);
 *   - in-place regions in Markdown guidance, between
 *     `<!-- rules: <selector> -->` and `<!-- /rules -->`, or inline between
 *     `<!-- rule: <id> -->` and `<!-- /rule -->`.
 *
 * The category-pack rule lists and foundation bullets are generated by
 * tools/generate-machine-docs.mjs from the same records.
 *
 * Checks (always run; --check also fails on any differing output):
 *   - record lint: strict frontmatter, unique ids, required sections;
 *   - schema placements outside the generated regions equal the
 *     hand-maintained schema;
 *   - with a starlims-lsp catalog: every lsp:diag/lsp:fmt in enforced_by is an
 *     active catalog entry; severity and status disagreements, and catalog
 *     schema_refs into generated regions that do not resolve, are warnings.
 *
 * The record examples are validated with the LSP binary by
 * tools/check-skill-examples.mjs.
 *
 * Usage:
 *   bun tools/generate-rules.mjs [--check] [--lsp-catalog <dir>]
 *
 * --lsp-catalog defaults to ../starlims-lsp/catalog. Without the flag a
 * missing catalog is skipped with a note; with it, a missing catalog fails.
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import YAML from 'yaml';
import {
  DOMAINS,
  REPO_ROOT,
  RULES_DIR,
  RulesError,
  liveRecords,
  loadRules,
  parseSelector,
  plainRule,
  renderRegion,
  repoRel,
  selectRecords,
} from './lib/rules.mjs';

const CHECK_ONLY = process.argv.includes('--check');
const catalogArg = process.argv.indexOf('--lsp-catalog');
const CATALOG_REQUIRED = catalogArg !== -1;
const CATALOG_DIR = resolve(
  REPO_ROOT,
  CATALOG_REQUIRED ? process.argv[catalogArg + 1] : '../starlims-lsp/catalog'
);

const SCHEMA_PATH = resolve(REPO_ROOT, 'ssl-style-guide/ssl-style-guide.schema.yaml');
const SCHEMA_BASE_PATH = resolve(RULES_DIR, 'schema-base.yaml');
const INDEX_PATH = resolve(RULES_DIR, 'INDEX.md');
// Markdown files under these roots may carry generated regions.
const REGION_ROOTS = ['agent-guides', 'ssl-style-guide'];
const REGION_SKIP = new Set(['node_modules', 'machine']);

const RULE_TAG = { tag: '!rule', resolve: (value) => value, identify: () => false };
const YAML_OUTPUT = { indentSeq: true };

// Keep one-line double-quoted strings on one line, as the hand-written schema
// does; the default stringifier folds them at lineWidth like block scalars.
function unfoldedDoubleQuotes(tags) {
  return tags.map((tag) => {
    if (tag.tag !== 'tag:yaml.org,2002:str' || typeof tag.stringify !== 'function') return tag;
    return {
      ...tag,
      stringify(item, ctx, onComment, onChompKeep) {
        const value = String(item.value);
        if (item.type === 'QUOTE_DOUBLE' && !value.includes('\n')) return JSON.stringify(value);
        return tag.stringify(item, ctx, onComment, onChompKeep);
      },
    };
  });
}

const problems = [];
const warnings = [];

// ---------------------------------------------------------------------------
// rules/INDEX.md

function renderIndex(records) {
  const lines = [
    '# Rules index',
    '',
    'Generated by `tools/generate-rules.mjs` from the records in this',
    'directory. Do not edit by hand; see [README.md](README.md).',
  ];
  for (const domain of DOMAINS) {
    const inDomain = records.filter((r) => r.domain === domain);
    if (inDomain.length === 0) continue;
    lines.push('', `## ${domain} (${inDomain.length})`, '');
    lines.push('| Id | Level | Severity | Enforced by | Rule |', '|---|---|---|---|---|');
    for (const r of inDomain) {
      const id = `[\`${r.id}\`](${r.domain}/${r.id}.md)${r.status === 'active' ? '' : ` (${r.status})`}`;
      const enforced = r.enforced_by.map((e) => `\`${e}\``).join(', ');
      lines.push(`| ${id} | ${r.level} | ${r.severity} | ${enforced} | ${r.rule.replace(/\|/g, '\\|')} |`);
    }
  }
  return `${lines.join('\n')}\n`;
}

// ---------------------------------------------------------------------------
// Schema

function placementsByPath(records) {
  const map = new Map();
  for (const r of liveRecords(records)) {
    for (const p of r.schema ?? []) {
      const key = `${p.path}\u0000${r.id}`;
      if (map.has(key)) problems.push(`${r.file}: two schema placements for path ${p.path}`);
      map.set(key, { record: r, placement: p });
    }
  }
  return map;
}

function lintEntry(doc, record, placement) {
  const node = doc.createNode({
    rule: record.id,
    severity: record.severity,
    message: placement.message ?? plainRule(record),
  });
  node.get('message', true).type = 'QUOTE_DOUBLE';
  return node;
}

function placementNode(doc, record, placement) {
  switch (placement.form) {
    case 'lint':
      return lintEntry(doc, record, placement);
    case 'rule_text': {
      const node = doc.createNode({ level: record.level, rule: placement.message ?? plainRule(record) });
      node.get('rule', true).type = 'QUOTE_DOUBLE';
      return node;
    }
    case 'text': {
      const node = doc.createNode(placement.message ?? plainRule(record));
      node.type = 'QUOTE_DOUBLE';
      return node;
    }
    default: {
      const node = doc.createNode(placement.value);
      if (YAML.isScalar(node)) node.comment = ` ${plainRule(record)}`;
      return node;
    }
  }
}

/** Generated region paths: the leaf mappings two levels into schema-base. */
function generatedRegionPaths(base) {
  const paths = [];
  for (const top of base.contents.items) {
    if (!YAML.isMap(top.value)) {
      problems.push(`rules/schema-base.yaml: ${top.key.value} must be a mapping of generated subtrees`);
      continue;
    }
    for (const sub of top.value.items) paths.push([top.key.value, sub.key.value]);
  }
  return paths;
}

function renderSchemaRegions(records) {
  const base = YAML.parseDocument(readFileSync(SCHEMA_BASE_PATH, 'utf8'), { customTags: [RULE_TAG] });
  if (base.errors.length > 0) {
    problems.push(`rules/schema-base.yaml: ${base.errors[0].message}`);
    return [];
  }
  const placements = placementsByPath(records);
  const consumed = new Set();
  const regions = [];
  const byId = new Map(records.map((r) => [r.id, r]));

  for (const path of generatedRegionPaths(base)) {
    const dotted = path.join('.');
    const node = base.getIn(path, true).clone();
    const out = new YAML.Document(undefined, { customTags: unfoldedDoubleQuotes });
    YAML.visit(node, {
      Scalar(key, scalar, ancestors) {
        if (scalar.tag !== '!rule') return undefined;
        const keys = [...path];
        for (const ancestor of ancestors) {
          if (YAML.isPair(ancestor)) keys.push(ancestor.key.value);
        }
        const at = keys.join('.');
        const id = String(scalar.value).trim();
        const record = byId.get(id);
        const hit = placements.get(`${at}\u0000${id}`);
        if (!record) {
          problems.push(`rules/schema-base.yaml: !rule ${id} at ${at} names no record`);
          return undefined;
        }
        if (!hit) {
          problems.push(`rules/schema-base.yaml: !rule ${id} at ${at} has no matching placement in ${record.file}`);
          return undefined;
        }
        consumed.add(`${at}\u0000${id}`);
        return placementNode(out, hit.record, hit.placement);
      },
    });
    out.contents = out.createNode({});
    out.contents.items.push(new YAML.Pair(new YAML.Scalar(path[path.length - 1]), node));
    const indent = '  '.repeat(path.length);
    const text = out
      .toString({ ...YAML_OUTPUT, lineWidth: 80 - indent.length })
      .trimEnd()
      .split('\n')
      .map((line) => (line ? indent + line : line))
      .join('\n');
    regions.push({ dotted, indent, text });
  }

  // Placements inside a generated region must have a slot; placements
  // outside are verified against the hand-maintained schema.
  const schema = YAML.parse(readFileSync(SCHEMA_PATH, 'utf8'))?.ssl_style_guide ?? {};
  for (const [key, { record, placement }] of placements) {
    const inRegion = regions.some((g) => placement.path === g.dotted || placement.path.startsWith(`${g.dotted}.`));
    if (inRegion) {
      if (!consumed.has(key)) {
        problems.push(`${record.file}: placement at ${placement.path} has no !rule ${record.id} slot in rules/schema-base.yaml`);
      }
      continue;
    }
    verifyPlacement(schema, record, placement);
  }
  return regions;
}

function getPath(object, dotted) {
  let current = object;
  for (const segment of dotted.split('.')) {
    if (Array.isArray(current)) {
      current = current.find((item) => item && item.rule === segment);
    } else if (current && typeof current === 'object') {
      current = current[segment];
    } else {
      return undefined;
    }
    if (current === undefined) return undefined;
  }
  return current;
}

function verifyPlacement(schema, record, placement) {
  const actual = getPath(schema, placement.path);
  const where = `${record.file}: schema placement ${placement.path}`;
  if (actual === undefined) {
    problems.push(`${where} does not exist in the schema`);
    return;
  }
  if (placement.form === 'value') {
    if (JSON.stringify(actual) !== JSON.stringify(placement.value)) {
      problems.push(`${where} is ${JSON.stringify(actual)} in the schema, not ${JSON.stringify(placement.value)}`);
    }
    return;
  }
  if (placement.form === 'text') {
    // A text placement is a string value, or one string in a list.
    const text = placement.message ?? plainRule(record);
    const found = Array.isArray(actual) ? actual.includes(text) : actual === text;
    if (!found) problems.push(`${where} has no string equal to ${JSON.stringify(text)}`);
    return;
  }
  if (!Array.isArray(actual)) {
    problems.push(`${where} is not a list in the schema`);
    return;
  }
  const want = placement.form === 'lint'
    ? { rule: record.id, severity: record.severity, message: placement.message ?? plainRule(record) }
    : { level: record.level, rule: placement.message ?? plainRule(record) };
  // An entry may carry keys the record does not supply (for example a
  // lint's `scope` note); the keys the record supplies must match.
  const matches = (item) =>
    item && typeof item === 'object' &&
    Object.entries(want).every(([key, value]) => JSON.stringify(item[key]) === JSON.stringify(value));
  if (!actual.some(matches)) {
    problems.push(`${where} has no entry matching ${JSON.stringify(want)}`);
  }
}

function spliceSchema(text, regions) {
  let result = text;
  for (const { dotted, indent, text: body } of regions) {
    const begin = `${indent}# BEGIN GENERATED ${dotted}`;
    const end = `${indent}# END GENERATED ${dotted}`;
    const lines = result.split('\n');
    const from = lines.findIndex((line) => line.startsWith(`${begin}:`) || line === begin);
    const to = lines.findIndex((line, index) => index > from && line === end);
    if (from === -1 || to === -1) {
      problems.push(`ssl-style-guide/ssl-style-guide.schema.yaml: missing "${begin}" / "${end}" markers`);
      continue;
    }
    lines.splice(from + 1, to - from - 1, body);
    result = lines.join('\n');
  }
  return result;
}

// ---------------------------------------------------------------------------
// Markdown regions

function listMarkdown() {
  const files = [];
  function walk(dir) {
    for (const entry of readdirSync(dir).sort()) {
      if (REGION_SKIP.has(entry)) continue;
      const full = resolve(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry.endsWith('.md')) files.push(full);
    }
  }
  for (const root of REGION_ROOTS) walk(resolve(REPO_ROOT, root));
  return files;
}

const OPEN_RE = /^([ \t]*)<!-- rules: (.+?) -->[ \t]*$/;
const CLOSE_RE = /^[ \t]*<!-- \/rules -->[ \t]*$/;
const INLINE_RE = /<!-- rule: ([a-z0-9_]+) -->[\s\S]*?<!-- \/rule -->/g;

function renderMarkdownRegions(file, text, records) {
  const where = repoRel(file);
  const byId = new Map(liveRecords(records).map((r) => [r.id, r]));
  const lines = text.split('\n');
  const out = [];
  let fence = null;
  let count = 0;
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const fenceMatch = line.match(/^[ \t]*(`{3,}|~{3,})/);
    if (fenceMatch) {
      if (!fence) fence = fenceMatch[1];
      else if (fenceMatch[1].startsWith(fence)) fence = null;
      out.push(line);
      continue;
    }
    if (fence) {
      out.push(line);
      continue;
    }
    const open = line.match(OPEN_RE);
    if (!open) {
      out.push(line.replace(INLINE_RE, (whole, id) => {
        count += 1;
        const record = byId.get(id);
        if (!record) {
          problems.push(`${where}:${index + 1}: <!-- rule: ${id} --> names no active record`);
          return whole;
        }
        return `<!-- rule: ${id} -->${record.rule}<!-- /rule -->`;
      }));
      continue;
    }
    count += 1;
    const close = lines.findIndex((l, i) => i > index && CLOSE_RE.test(l));
    if (close === -1) {
      problems.push(`${where}:${index + 1}: <!-- rules: ... --> has no <!-- /rules -->`);
      out.push(line);
      continue;
    }
    let parsed;
    try {
      parsed = parseSelector(open[2]);
    } catch (error) {
      problems.push(`${where}:${index + 1}: ${error.message}`);
      out.push(...lines.slice(index, close + 1));
      index = close;
      continue;
    }
    const selected = selectRecords(records, parsed.selector);
    // An id= selector lists its records in the order it names them.
    if (parsed.selector.id) {
      selected.sort((a, b) => parsed.selector.id.indexOf(a.id) - parsed.selector.id.indexOf(b.id));
    }
    if (selected.length === 0) problems.push(`${where}:${index + 1}: selector '${open[2]}' matches no record`);
    out.push(line, renderRegion(selected, parsed.format, open[1], parsed.wrap), lines[close]);
    index = close;
  }
  return { text: out.join('\n'), count };
}

// ---------------------------------------------------------------------------
// starlims-lsp catalog

function catalogEntry(kind, slug) {
  const dir = kind === 'diag' ? 'diagnostics' : 'formatting';
  const path = resolve(CATALOG_DIR, dir, `${slug}.md`);
  if (!existsSync(path)) return null;
  const raw = readFileSync(path, 'utf8');
  const end = raw.indexOf('\n---\n', 4);
  return YAML.parse(raw.slice(4, end));
}

function checkCatalog(records, schemaText) {
  if (!existsSync(CATALOG_DIR)) {
    if (CATALOG_REQUIRED) problems.push(`starlims-lsp catalog not found at ${CATALOG_DIR}`);
    else console.log(`Note: no starlims-lsp catalog at ${CATALOG_DIR}; enforced_by not resolved (pass --lsp-catalog).`);
    return;
  }
  for (const r of liveRecords(records)) {
    for (const item of r.enforced_by) {
      const match = item.match(/^lsp:(diag|fmt)\.(.+)$/);
      if (!match) continue;
      const entry = catalogEntry(match[1], match[2]);
      if (!entry) {
        problems.push(`${r.file}: enforced_by ${item} has no starlims-lsp catalog entry`);
        continue;
      }
      if (entry.status !== 'active') {
        problems.push(`${r.file}: enforced_by ${item} is '${entry.status}' in the starlims-lsp catalog`);
      }
      if (match[1] === 'diag' && entry.default_severity && entry.default_severity !== r.severity) {
        warnings.push(`${r.id}: severity ${r.severity}, but ${item} defaults to ${entry.default_severity}`);
      }
    }
    const sameSlug = catalogEntry('diag', r.id);
    if (sameSlug && sameSlug.status === 'removed') {
      warnings.push(`${r.id}: active here, but diag.${r.id} is 'removed' in the starlims-lsp catalog`);
    }
  }
  // Catalog schema_refs that point into a generated region must resolve.
  const schema = YAML.parse(schemaText)?.ssl_style_guide ?? {};
  const generated = [...schemaText.matchAll(/# BEGIN GENERATED ([a-z0-9_.]+)/g)].map((m) => m[1]);
  for (const dir of ['diagnostics', 'formatting', 'features']) {
    const full = resolve(CATALOG_DIR, dir);
    if (!existsSync(full)) continue;
    for (const name of readdirSync(full).filter((n) => n.endsWith('.md')).sort()) {
      const raw = readFileSync(resolve(full, name), 'utf8');
      const ref = raw.match(/^schema_ref: ([^\s#]+)/m)?.[1];
      if (!ref || ref === 'null') continue;
      if (!generated.some((g) => ref === g || ref.startsWith(`${g}.`))) continue;
      if (getPath(schema, ref) === undefined) {
        warnings.push(`starlims-lsp ${dir}/${name}: schema_ref ${ref} does not resolve in the generated schema`);
      }
    }
  }
}

// ---------------------------------------------------------------------------

function main() {
  let records;
  try {
    ({ records } = loadRules());
  } catch (error) {
    if (error instanceof RulesError) {
      console.error(error.message);
      process.exit(1);
    }
    throw error;
  }

  const outputs = [{ path: INDEX_PATH, content: renderIndex(records) }];

  const schemaText = readFileSync(SCHEMA_PATH, 'utf8');
  const regions = renderSchemaRegions(records);
  const nextSchema = spliceSchema(schemaText, regions);
  outputs.push({ path: SCHEMA_PATH, content: nextSchema });

  let regionCount = 0;
  for (const file of listMarkdown()) {
    const text = readFileSync(file, 'utf8');
    if (!text.includes('<!-- rules: ') && !text.includes('<!-- rule: ')) continue;
    const { text: next, count } = renderMarkdownRegions(file, text, records);
    regionCount += count;
    outputs.push({ path: file, content: next });
  }

  checkCatalog(records, nextSchema);

  for (const warning of warnings) console.warn(`warning: ${warning}`);
  if (problems.length > 0) {
    console.error(`Rules check failed (${problems.length}):`);
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }

  const drift = [];
  for (const output of outputs) {
    const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : null;
    if (current === output.content) continue;
    if (CHECK_ONLY) drift.push(repoRel(output.path));
    else writeFileSync(output.path, output.content, 'utf8');
    if (!CHECK_ONLY) console.log(`  - wrote ${repoRel(output.path)}`);
  }

  const summary =
    `${records.length} rule records, ${regions.length} schema region(s), ` +
    `${regionCount} Markdown region(s)`;
  if (CHECK_ONLY) {
    if (drift.length > 0) {
      console.error('Rule outputs are out of sync:');
      for (const label of drift) console.error(`  - ${label}`);
      console.error('Run: bun tools/generate-rules.mjs, then bun tools/generate-machine-docs.mjs');
      process.exit(1);
    }
    console.log(`Rule outputs in sync (${summary}).`);
    return;
  }
  console.log(`Generated rule outputs (${summary}).`);
  console.log('Next: bun tools/generate-machine-docs.mjs, then bun run bundle-data in ssl-mcp-server/.');
}

main();
